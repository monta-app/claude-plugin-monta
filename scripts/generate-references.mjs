export const PUBLIC_REFERENCES = {
  apiName: "Monta Public API",
  docsIndexOriginEnv: "PUBLIC_DOCS_INDEX_ORIGIN",
  outDir: fileURLToPath(new URL("../plugins/monta-public-api/skills/monta-public-api/references/", import.meta.url)),
  specs: [
    {
      label: null,
      specUrl: "https://public-api.monta.com/swagger/monta-public-api-2023-09-14.yml",
      docsOrigin: "https://docs.public-api.monta.com",
      docsIndexPath: "/openapi/monta-public-api-endpoints.txt",
      indexFile: "endpoints.md",
      intro: PUBLIC_INTRO,
      tagIntro: `HTTP only, none of these is an MCP tool, see \`../endpoints.md\`. ${SAFETY_LEGEND}`,
      operationIdHeader: "Operation ID",
    },
  ],
};

const deprecatedIntro = (apiName) => `# Deprecated ${apiName} operations

Operations the ${apiName} spec marks as deprecated. Do not use them for new work. The note quotes the spec, which names the replacement when there is one.`;

const schemasIntro = (apiName) => `# ${apiName} schemas

Component schemas of the ${apiName} spec: the first sentence of each description and the required fields.`;

const ENDPOINT_HEADERS = ["Method and path", "Summary", "Query filters", "Safety", "Docs"];

// UTF-16 code-unit order, so the output does not depend on the ICU version of the Node that generates it
const byText = (a, b) => {
  if (a === b) {
    return 0;
  }
  return a < b ? -1 : 1;
};

const byPathThenMethod = (a, b) => byText(a.path, b.path) || METHODS.indexOf(a.method) - METHODS.indexOf(b.method);

const escapeCell = (text) => text.replace(/\s*\n\s*/g, " ").replaceAll("|", "\\|").trim();

const tableRow = (cells) => `| ${cells.map(escapeCell).join(" | ")} |`;

const table = (headers, rows) => [tableRow(headers), `|${headers.map(() => "---").join("|")}|`, ...rows.map(tableRow)].join("\n");

const generatedFile = (apiName, intro, sections) => `${[generatedNotice(apiName), intro, ...sections].join("\n\n")}\n`;

const section = (label, content) => (label !== null ? `## ${label}\n\n${content}` : content);

const paragraphs = (text) =>
  text
    .split(PARAGRAPH_BREAK)
    .map((paragraph) => paragraph.trim())
    .filter((paragraph) => paragraph !== "");

const deprecationNote = (description) => {
  const deprecationParagraphs = paragraphs(description).filter((paragraph) => /deprecat/i.test(paragraph));
  if (deprecationParagraphs.length === 0) {
    return description;
  }
  return deprecationParagraphs.join(" ");
};

const firstSentence = (description) => {
  const [firstParagraph = ""] = paragraphs(description);
  return firstParagraph.split(/(?<=\.)\s/)[0];
};

const indexedOperations = (spec, docsPages, entry) =>
  specOperations(spec, docsPages, entry).map(({ method, path, operation, docsUrl }) => ({
    method,
    path,
    tag: operation.tags?.[0] ?? UNTAGGED,
    operationId: operation.operationId ?? NO_OPERATION_ID,
    summary: operation.summary ?? "",
    description: operation.description ?? "",
    queryFilters: (operation.parameters ?? []).filter((parameter) => parameter.in === "query").map(({ name }) => name),
    safety: operationSafety(method, operation.operationId),
    deprecated: operation.deprecated === true,
    docsLink: docsUrl !== null ? `[docs](${docsUrl})` : "",
  }));

const methodAndPath = ({ method, path }) => `${method.toUpperCase()} ${path}`;

const endpointRow = (operation) => [
  operation.operationId,
  methodAndPath(operation),
  operation.summary,
  operation.queryFilters.join(", "),
  operation.safety,
  operation.docsLink,
];

const endpointFiles = (apiName, { label, indexFile, intro, tagIntro, operationIdHeader }, operations) => {
  const tagDir = label !== null ? `endpoints/${label}` : "endpoints";
  const currentOperations = operations.filter(({ deprecated }) => !deprecated);
  const operationsByTag = Map.groupBy(currentOperations, ({ tag }) => tag);
  const tagFileSlug = slugifyWithCounter();
  const tags = [...operationsByTag.keys()].sort(byText).map((tag) => ({
    tag,
    operations: operationsByTag.get(tag).toSorted(byPathThenMethod),
    file: `${tagDir}/${tagFileSlug(tag)}.md`,
  }));
  const indexRows = tags.map(({ tag, operations, file }) => [tag, String(operations.length), `[${file}](${file})`]);
  const tagFiles = tags.map(({ tag, operations, file }) => {
    const endpointTable = table([operationIdHeader, ...ENDPOINT_HEADERS], operations.map(endpointRow));
    const heading = label !== null ? `# ${tag} (${label})` : `# ${tag}`;
    return [file, generatedFile(apiName, `${heading}\n\n${tagIntro}`, [endpointTable])];
  });
  return [[indexFile, generatedFile(apiName, intro, [table(["Tag", "Operations", "File"], indexRows)])], ...tagFiles];
};

const deprecatedSection = (label, operations) => {
  const rows = operations
    .filter(({ deprecated }) => deprecated)
    .toSorted(byPathThenMethod)
    .map((operation) => [operation.operationId, methodAndPath(operation), deprecationNote(operation.description), operation.docsLink]);
  return section(label, table(["Operation ID", "Method and path", "Deprecation note", "Docs"], rows));
};

const schemasSection = (label, spec) => {
  const schemas = Object.entries(spec.components?.schemas ?? {});
  const rows = schemas
    .toSorted(([a], [b]) => byText(a, b))
    .map(([name, schema]) => [name, firstSentence(schema.description ?? ""), (schema.required ?? []).join(", ")])
    .filter(([, description, requiredFields]) => description !== "" || requiredFields !== "");
  return section(label, table(["Name", "Description", "Required fields"], rows));
};

// parsedSpecs and docsIndexes hold the parsed spec and docs index of each entry in references.specs, in the same order
export const renderReferences = ({ apiName, specs: specEntries }, parsedSpecs, docsIndexes) => {
  const sources = specEntries.map((entry, index) => ({
    entry,
    spec: parsedSpecs[index],
    operations: indexedOperations(parsedSpecs[index], docsIndexes[index], entry),
  }));
  return {
    ...Object.fromEntries(sources.flatMap(({ entry, operations }) => endpointFiles(apiName, entry, operations))),
    "deprecated.md": generatedFile(
      apiName,
      deprecatedIntro(apiName),
      sources.map(({ entry, operations }) => deprecatedSection(entry.label, operations)),
    ),
    "schemas.md": generatedFile(
      apiName,
      schemasIntro(apiName),
      sources.map(({ entry, spec }) => schemasSection(entry.label, spec)),
    ),
  };
};

// Clears the tag files first, so a tag dropped from the spec loses its file
export const writeReferences = (outDir, references) => {
  rmSync(join(outDir, "endpoints"), { recursive: true, force: true });
  for (const [file, content] of Object.entries(references)) {
    const filePath = join(outDir, file);
    mkdirSync(dirname(filePath), { recursive: true });
    writeFileSync(filePath, content);
  }
};

const fetchText = async (url) => {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Fetching ${url} failed with HTTP ${response.status}`);
  }
  return response.text();
};

const loadSpec = async (specUrl) => {
  const specText = await fetchText(specUrl);
  return parse(specText);
};

const loadDocsIndex = async (indexUrl) => {
  const indexText = await fetchText(indexUrl);
  return parseDocsIndex(indexText);
};

const main = async () => {
  for (const references of [PARTNER_REFERENCES, PUBLIC_REFERENCES]) {
    const indexOrigin = process.env[references.docsIndexOriginEnv];
    const specs = await Promise.all(references.specs.map(({ specUrl }) => loadSpec(specUrl)));
    const docsIndexes = await Promise.all(references.specs.map((entry) => loadDocsIndex(docsIndexUrl(entry, indexOrigin))));
    writeReferences(references.outDir, renderReferences(references, specs, docsIndexes));
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
