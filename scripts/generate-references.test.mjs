import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, test } from "node:test";
import { parse } from "yaml";
import { renderReferences, writeReferences } from "./generate-references.mjs";

const fixtureSpec = (fileName) => parse(readFileSync(new URL(`./fixtures/${fileName}`, import.meta.url), "utf8"));

const specs = { v1Spec: fixtureSpec("v1.yml"), v2Spec: fixtureSpec("v2.yml") };

const references = renderReferences(specs);

const lineContaining = (fileName, text) => references[fileName].split("\n").find((line) => line.includes(text));

const endpointFiles = Object.entries(references).filter(([fileName]) => fileName.startsWith("endpoints"));

const tempDir = () => {
  const dir = mkdtempSync(join(tmpdir(), "generate-references-"));
  after(() => rmSync(dir, { recursive: true }));
  return dir;
};

test("every generated file starts with the do-not-edit notice", () => {
  const notice =
    "<!-- Generated by scripts/generate-references.mjs from the Monta API OpenAPI spec. Do not edit by hand; regenerate with `npm run generate`. -->";

  const firstLines = Object.values(references).map((content) => content.split("\n")[0]);

  assert.deepEqual(new Set(firstLines), new Set([notice]));
});

test("the endpoints index lists each tag in alphabetical order with its operation count and file, untagged operations under Other", () => {
  const indexRows = references["endpoints.md"].split("\n").filter((line) => line.startsWith("| ")).slice(1);

  assert.deepEqual(indexRows, [
    "| Charge Points | 1 | [endpoints/v1/charge-points.md](endpoints/v1/charge-points.md) |",
    "| Consumers | 1 | [endpoints/v1/consumers.md](endpoints/v1/consumers.md) |",
    "| Other | 1 | [endpoints/v1/other.md](endpoints/v1/other.md) |",
    "| Teams | 2 | [endpoints/v1/teams.md](endpoints/v1/teams.md) |",
  ]);
});

test("an endpoint row lists tool, method and path, summary, query filters, safety and docs link", () => {
  const row = lineContaining("endpoints/v1/teams.md", "get-teams");

  assert.equal(row, "| get-teams | GET /api/v1/teams | Retrieve teams | operatorId, page | R | [docs](https://developer.monta.com/api/v1/retrieve-teams) |");
});

test("an operation without an operation id shows (none) as its tool", () => {
  const row = lineContaining("endpoints/v1/other.md", "GET /api/v1/ping");

  assert.equal(row, "| (none) | GET /api/v1/ping | Ping |  | R | [docs](https://developer.monta.com/api/v1/ping) |");
});

test("tags that slug to the same file name get numbered files", () => {
  const v1Spec = {
    paths: {
      "/a": { get: { tags: ["Charge Points"], operationId: "get-a" } },
      "/b": { get: { tags: ["Charge-Points"], operationId: "get-b" } },
    },
  };

  const tagFiles = Object.keys(renderReferences({ v1Spec, v2Spec: {} })).filter((fileName) => fileName.startsWith("endpoints/v1/"));

  assert.deepEqual(tagFiles, ["endpoints/v1/charge-points.md", "endpoints/v1/charge-points-2.md"]);
});

test("pipes inside table cells are escaped", () => {
  const row = lineContaining("endpoints/v1/charge-points.md", "get-charge-point-logs");

  assert.match(row, / Charge point logs \\\| OCPP messages /);
});

test("the endpoint files leave out deprecated operations", () => {
  const filesWithDeprecated = endpointFiles.filter(([, content]) => /get-auth-information|resolve-report|get-afir-charge-points/.test(content));

  assert.deepEqual(filesWithDeprecated, []);
});

test("the v2 index and tag files say they are HTTP only and not MCP tools", () => {
  assert.match(references["endpoints-v2.md"], /^# Monta API v2 endpoints \(HTTP only\)$/m);
  assert.match(references["endpoints-v2.md"], /none of these operations is an MCP tool/);
  assert.match(references["endpoints/v2/teams.md"], /HTTP only with the `Monta-Version: v2` header, none of these is an MCP tool/);
});

test("a deprecated operation quotes the paragraph of its description that mentions the deprecation", () => {
  const row = lineContaining("deprecated.md", "get-afir-charge-points");

  assert.equal(
    row,
    "| get-afir-charge-points | GET /api/v1/afir/charge-points | **Deprecated.** Use the AFIR charge points endpoint of the [Public API](https://developer.monta.com/docs/public-api) instead. | [docs](https://developer.monta.com/api/v2/retrieve-afir-charge-points) |",
  );
});

test("a deprecated operation quotes its whole description when no paragraph mentions the deprecation", () => {
  const row = lineContaining("deprecated.md", "resolve-report");

  assert.equal(
    row,
    "| resolve-report | POST /api/v1/reports/{reportId}/resolve | For alerts use `/alerts`.<br/><br/>Required scope: `reports:write` | [docs](https://developer.monta.com/api/v1/resolve-a-report) |",
  );
});

test("a deprecated operation keeps its docs page number among operations with the same summary", () => {
  const row = lineContaining("endpoints/v1/consumers.md", "get-current-consumer");

  assert.match(row, /\[docs\]\(https:\/\/developer\.monta\.com\/api\/v1\/obtain-information-about-current-api-consumer-2\)/);
});

test("a schema row lists the first sentence of its description and its required fields", () => {
  const row = lineContaining("schemas.md", "| Team |");

  assert.equal(row, "| Team | A team owns charge points. | id, name |");
});

test("schemas without a description or required fields are left out", () => {
  assert.doesNotMatch(references["schemas.md"], /\| Ping \|/);
});

test("every absolute link in the generated files points to developer.monta.com", () => {
  const urls = Object.values(references).flatMap((content) => [...content.matchAll(/https?:\/\/[^\s)|]+/g)].map(([url]) => url));
  const hosts = new Set(urls.map((url) => new URL(url).host));

  assert.deepEqual([...hosts], ["developer.monta.com"]);
});

test("rendering the same specs twice gives identical output", () => {
  assert.deepEqual(renderReferences(specs), references);
});

test("writing the references removes tag files of tags no longer in the spec", () => {
  const outDir = tempDir();
  mkdirSync(join(outDir, "endpoints", "v1"), { recursive: true });
  writeFileSync(join(outDir, "endpoints", "v1", "dropped-tag.md"), "stale");

  writeReferences(outDir, references);

  assert.equal(existsSync(join(outDir, "endpoints", "v1", "dropped-tag.md")), false);
});
