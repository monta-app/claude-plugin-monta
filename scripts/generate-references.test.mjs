import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, test } from "node:test";
import { parse } from "yaml";
import { parseDocsIndex } from "./docs-links.mjs";
import { PARTNER_REFERENCES, PUBLIC_REFERENCES, renderReferences, writeReferences } from "./generate-references.mjs";

const fixtureText = (fileName) => readFileSync(new URL(`./fixtures/${fileName}`, import.meta.url), "utf8");

const fixtureSpec = (fileName) => parse(fixtureText(fileName));

const fixtureDocsIndex = (fileName) => parseDocsIndex(fixtureText(fileName));

const partnerSpecs = [fixtureSpec("v1.yml"), fixtureSpec("v2.yml")];

const partnerDocsIndexes = [fixtureDocsIndex("v1-endpoints.txt"), fixtureDocsIndex("v2-endpoints.txt")];

const publicDocsIndexes = [fixtureDocsIndex("public-endpoints.txt")];

const references = renderReferences(PARTNER_REFERENCES, partnerSpecs, partnerDocsIndexes);

const publicReferences = renderReferences(PUBLIC_REFERENCES, [fixtureSpec("public.yml")], publicDocsIndexes);

const linkTargets = (content) => [...content.matchAll(/\]\((https?:\/\/[^)\s]+)\)/g)].map(([, url]) => url);

const lineContaining = (fileName, text) => references[fileName].split("\n").find((line) => line.includes(text));

const endpointFiles = Object.entries(references).filter(([fileName]) => fileName.startsWith("endpoints"));

const tempDir = () => {
  const dir = mkdtempSync(join(tmpdir(), "generate-references-"));
  after(() => rmSync(dir, { recursive: true }));
  return dir;
};

test("every generated file starts with the do-not-edit notice", () => {
  const notice =
    "<!-- Generated by scripts/generate-references.mjs from the Monta API OpenAPI spec. Do not edit by hand; regenerate with `npm run generate`. -->";

  const firstLines = Object.values(references).map((content) => content.split("\n")[0]);

  assert.deepEqual(new Set(firstLines), new Set([notice]));
});

test("the endpoints index lists each tag in alphabetical order with its operation count and file, untagged operations under Other", () => {
  const indexRows = references["endpoints.md"].split("\n").filter((line) => line.startsWith("| ")).slice(1);

  assert.deepEqual(indexRows, [
    "| Charge Points | 1 | [endpoints/v1/charge-points.md](endpoints/v1/charge-points.md) |",
    "| Consumers | 1 | [endpoints/v1/consumers.md](endpoints/v1/consumers.md) |",
    "| Other | 1 | [endpoints/v1/other.md](endpoints/v1/other.md) |",
    "| Teams | 2 | [endpoints/v1/teams.md](endpoints/v1/teams.md) |",
  ]);
});

test("an endpoint row lists tool, method and path, summary, query filters, safety and docs link", () => {
  const row = lineContaining("endpoints/v1/teams.md", "get-teams");

  assert.equal(row, "| get-teams | GET /api/v1/teams | Retrieve teams | operatorId, page | R | [docs](https://developer.monta.com/api/v1/teams) |");
});

test("an operation the docs index does not list yet has an empty docs cell", () => {
  const v1DocsIndex = parseDocsIndex(fixtureText("v1-endpoints.txt").replace(/^GET \/api\/v1\/teams .*$/m, ""));

  const teamsFile = renderReferences(PARTNER_REFERENCES, partnerSpecs, [v1DocsIndex, partnerDocsIndexes[1]])["endpoints/v1/teams.md"];
  const row = teamsFile.split("\n").find((line) => line.includes("get-teams"));

  assert.equal(row, "| get-teams | GET /api/v1/teams | Retrieve teams | operatorId, page | R |  |");
});

test("an operation without an operation id shows (none) as its tool", () => {
  const row = lineContaining("endpoints/v1/other.md", "GET /api/v1/ping");

  assert.equal(row, "| (none) | GET /api/v1/ping | Ping |  | R | [docs](https://developer.monta.com/api/v1/ping) |");
});

test("tags that slug to the same file name get numbered files", () => {
  const v1Spec = {
    paths: {
      "/a": { get: { tags: ["Charge Points"], operationId: "get-a" } },
      "/b": { get: { tags: ["Charge-Points"], operationId: "get-b" } },
    },
  };
  const v1DocsIndex = parseDocsIndex("GET /a | A | https://developer.monta.com/api/v1/a\nGET /b | B | https://developer.monta.com/api/v1/b");

  const tagFiles = Object.keys(renderReferences(PARTNER_REFERENCES, [v1Spec, {}], [v1DocsIndex, new Map()])).filter((fileName) => fileName.startsWith("endpoints/v1/"));

  assert.deepEqual(tagFiles, ["endpoints/v1/charge-points.md", "endpoints/v1/charge-points-2.md"]);
});

test("pipes inside table cells are escaped", () => {
  const row = lineContaining("endpoints/v1/charge-points.md", "get-charge-point-logs");

  assert.match(row, / Charge point logs \\\| OCPP messages /);
});

test("the endpoint files leave out deprecated operations", () => {
  const filesWithDeprecated = endpointFiles.filter(([, content]) => /get-auth-information|resolve-report|get-afir-charge-points/.test(content));

  assert.deepEqual(filesWithDeprecated, []);
});

test("the v2 index and tag files say they are HTTP only and not MCP tools", () => {
  assert.match(references["endpoints-v2.md"], /^# Monta API v2 endpoints \(HTTP only\)$/m);
  assert.match(references["endpoints-v2.md"], /none of these operations is an MCP tool/);
  assert.match(references["endpoints/v2/teams.md"], /HTTP only with the `Monta-Version: v2` header, none of these is an MCP tool/);
});

test("a deprecated operation quotes the paragraph of its description that mentions the deprecation", () => {
  const row = lineContaining("deprecated.md", "get-afir-charge-points");

  assert.equal(
    row,
    "| get-afir-charge-points | GET /api/v1/afir/charge-points | **Deprecated.** Use the AFIR charge points endpoint of the [Public API](https://developer.monta.com/docs/public-api) instead. | [docs](https://developer.monta.com/api/v2/afir/charge-points) |",
  );
});

test("a deprecated operation quotes its whole description when no paragraph mentions the deprecation", () => {
  const row = lineContaining("deprecated.md", "resolve-report");

  assert.equal(
    row,
    "| resolve-report | POST /api/v1/reports/{reportId}/resolve | For alerts use `/alerts`.<br/><br/>Required scope: `reports:write` | [docs](https://developer.monta.com/api/v1/reports/reportId/resolve) |",
  );
});

test("a schema row lists the first sentence of its description and its required fields", () => {
  const row = lineContaining("schemas.md", "| Team |");

  assert.equal(row, "| Team | A team owns charge points. | id, name |");
});

test("schemas without a description or required fields are left out", () => {
  assert.doesNotMatch(references["schemas.md"], /\| Ping \|/);
});

test("every absolute link in the generated files points to the docs site of its API", () => {
  const linkedHosts = (apiReferences) => [...new Set(Object.values(apiReferences).flatMap(linkTargets).map((url) => new URL(url).host))];

  assert.deepEqual(linkedHosts(references), ["developer.monta.com"]);
  assert.deepEqual(linkedHosts(publicReferences), ["docs.public-api.monta.com"]);
});

test("the public references link every operation to its docs.public-api.monta.com page", () => {
  const docsLinks = Object.values(publicReferences).flatMap((content) => [...content.matchAll(/\[docs\]\(([^)]+)\)/g)].map(([, url]) => url));

  assert.deepEqual(docsLinks.toSorted(), [
    "https://docs.public-api.monta.com/api/v1/auth/me",
    "https://docs.public-api.monta.com/api/v1/auth/refresh",
    "https://docs.public-api.monta.com/api/v1/auth/token",
    "https://docs.public-api.monta.com/api/v1/charges/chargeId/stop",
    "https://docs.public-api.monta.com/api/v1/charges/get",
    "https://docs.public-api.monta.com/api/v1/charges/post",
    "https://docs.public-api.monta.com/api/v1/wallets/personal",
  ]);
});

test("the public endpoint files say they are HTTP only with no MCP tools", () => {
  assert.match(publicReferences["endpoints.md"], /^# Monta Public API endpoints \(HTTP only\)$/m);
  assert.match(publicReferences["endpoints.md"], /The Public API has no MCP server, so none of these operations is an MCP tool/);
  assert.match(publicReferences["endpoints/charges.md"], /HTTP only, none of these is an MCP tool/);
});

test("the public references keep the tag files and sections free of a version", () => {
  const tagFiles = Object.keys(publicReferences).filter((fileName) => fileName.startsWith("endpoints/"));

  assert.deepEqual(tagFiles, ["endpoints/authentication.md", "endpoints/charges.md"]);
  assert.match(publicReferences["endpoints/charges.md"], /^# Charges$/m);
  assert.doesNotMatch(publicReferences["schemas.md"], /^## /m);
});

test("stop-charge is destructive in the public references", () => {
  const row = publicReferences["endpoints/charges.md"].split("\n").find((line) => line.includes("stop-charge"));

  assert.equal(row, "| stop-charge | POST /api/v1/charges/{chargeId}/stop | Stop a charge. |  | D | [docs](https://docs.public-api.monta.com/api/v1/charges/chargeId/stop) |");
});

test("a deprecated public operation is listed in deprecated.md and left out of the endpoint files", () => {
  const endpointFilesWithDeprecated = Object.entries(publicReferences).filter(
    ([fileName, content]) => fileName.startsWith("endpoints") && content.includes("get-personal-wallet"),
  );

  assert.deepEqual(endpointFilesWithDeprecated, []);
  assert.match(publicReferences["deprecated.md"], /\| get-personal-wallet \| GET \/api\/v1\/wallets\/personal \| Deprecated, use `\/api\/v1\/wallet-transactions` instead\. \|/);
});

test("rendering the same specs twice gives identical output", () => {
  assert.deepEqual(renderReferences(PARTNER_REFERENCES, partnerSpecs, partnerDocsIndexes), references);
  assert.deepEqual(renderReferences(PUBLIC_REFERENCES, [fixtureSpec("public.yml")], publicDocsIndexes), publicReferences);
});

test("writing the references removes tag files of tags no longer in the spec", () => {
  const outDir = tempDir();
  mkdirSync(join(outDir, "endpoints", "v1"), { recursive: true });
  writeFileSync(join(outDir, "endpoints", "v1", "dropped-tag.md"), "stale");

  writeReferences(outDir, references);

  assert.equal(existsSync(join(outDir, "endpoints", "v1", "dropped-tag.md")), false);
});
